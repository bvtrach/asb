#!/usr/bin/env python3
"""Render AutoUML's Graphviz DOT into a dependency-free SVG fallback.

Graphviz's `dot` binary is preferred by the Makefile. This fallback keeps
`make build` self-contained on development machines that do not have Graphviz:
it preserves AutoUML's nodes and relationships in a deterministic SVG grid.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path


NODE = re.compile(r'^\s*"([^"]+)"\s+\[label=')
EDGE = re.compile(r'^\s*"([^"]+)"\s+->\s+"([^"]+)"')


def title(identifier: str) -> str:
    return identifier.rsplit("_", 1)[-1].replace("-", " ")


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit("usage: render_dot_svg.py INPUT.dot OUTPUT.svg")
    source, destination = map(Path, sys.argv[1:])
    nodes: list[str] = []
    edges: list[tuple[str, str]] = []
    for line in source.read_text(encoding="utf-8").splitlines():
        node = NODE.match(line)
        if node and node.group(1) not in nodes:
            nodes.append(node.group(1))
        edge = EDGE.match(line)
        if edge:
            edges.append(edge.groups())
    columns, width, box_width, box_height = 4, 1120, 250, 82
    rows = max(1, (len(nodes) + columns - 1) // columns)
    height = 110 + rows * 118
    positions = {
        node: (40 + (index % columns) * 270, 70 + (index // columns) * 118)
        for index, node in enumerate(nodes)
    }
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" viewBox="0 0 %d %d">'
        % (width, height, width, height),
        '<title>ASB Rust UML class diagram</title>',
        '<defs><marker id="arrow" markerWidth="8" markerHeight="8" refX="7" refY="4" orient="auto"><path d="M0,0 L8,4 L0,8 z" fill="#4f5d75"/></marker></defs>',
        '<rect width="100%" height="100%" fill="#f8fafc"/>',
        '<text x="40" y="38" font-family="sans-serif" font-size="24" font-weight="700" fill="#172033">ASB Rust UML</text>',
        '<text x="40" y="58" font-family="sans-serif" font-size="13" fill="#526277">Generated by AutoUML; Graphviz-free fallback renderer</text>',
    ]
    for start, end in edges:
        if start not in positions or end not in positions:
            continue
        x1, y1 = positions[start]
        x2, y2 = positions[end]
        lines.append(
            '<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="#64748b" stroke-width="1.25" marker-end="url(#arrow)"/>'
            % (x1 + box_width // 2, y1 + box_height // 2, x2 + box_width // 2, y2 + box_height // 2)
        )
    for node in nodes:
        x, y = positions[node]
        label = html.escape(title(node))
        lines.extend(
            [
                '<rect x="%d" y="%d" width="%d" height="%d" rx="8" fill="#ffffff" stroke="#2563eb" stroke-width="1.5"/>'
                % (x, y, box_width, box_height),
                '<text x="%d" y="%d" font-family="sans-serif" font-size="15" font-weight="600" fill="#172033">%s</text>'
                % (x + 14, y + 34, label),
                '<text x="%d" y="%d" font-family="monospace" font-size="10" fill="#526277">%s</text>'
                % (x + 14, y + 57, html.escape(node)),
            ]
        )
    lines.append("</svg>")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
